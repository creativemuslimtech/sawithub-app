CREATE TABLE IF NOT EXISTS `t_sawit_hub_pendapatan` (
  `id_pendapatan` bigint unsigned NOT NULL AUTO_INCREMENT,
  `user_id` bigint unsigned NOT NULL,
  `id_lahan` bigint unsigned NOT NULL,
  `tanggal_panen` date NOT NULL,
  `total_janjang` int DEFAULT NULL,
  `total_berat_kg` decimal(12,2) NOT NULL,
  `pendapatan_kotor` decimal(14,2) NOT NULL,
  `biaya_total` decimal(14,2) NOT NULL,
  `pendapatan_bersih` decimal(14,2) GENERATED ALWAYS AS ((coalesce(`pendapatan_kotor`,0) - coalesce(`biaya_total`,0))) STORED,
  `catatan` text,
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `deleted_at` datetime DEFAULT NULL,
  PRIMARY KEY (`id_pendapatan`),
  UNIQUE KEY `idx_user_id_id_lahan_tanggal_panen_deleted_at` (`user_id`,`id_lahan`,`tanggal_panen`,`deleted_at`),
  KEY `idx_user_id` (`user_id`),
  KEY `idx_id_lahan` (`id_lahan`),
  KEY `idx_tanggal_panen` (`tanggal_panen`),
  KEY `idx_user_id_tanggal_panen` (`user_id`,`tanggal_panen` DESC),
  KEY `idx_user_id_id_lahan_tanggal_panen` (`user_id`,`id_lahan`,`tanggal_panen` DESC),
  KEY `idx_deleted_at` (`deleted_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
