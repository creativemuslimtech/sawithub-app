CREATE TABLE IF NOT EXISTS `t_sawit_admin_users` (
  `admin_user_id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `legacy_user_id` bigint unsigned DEFAULT NULL,
  `public_id` varchar(36) NOT NULL,
  `username` varchar(50) NOT NULL,
  `email_hash` varchar(64) NOT NULL,
  `email_enc` text NOT NULL,
  `full_name_enc` text,
  `phone_enc` text,
  `phone_hash` varchar(64) DEFAULT NULL,
  `password_hash` varchar(255) NOT NULL,
  `role` enum('admin','super_admin') NOT NULL DEFAULT 'admin',
  `is_active` tinyint(1) NOT NULL DEFAULT 1,
  `last_login_at` datetime DEFAULT NULL,
  `migrated_at` datetime DEFAULT NULL,
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `deleted_at` datetime DEFAULT NULL,
  PRIMARY KEY (`admin_user_id`),
  UNIQUE KEY `idx_admin_public_id` (`public_id`),
  UNIQUE KEY `idx_admin_email_hash` (`email_hash`),
  UNIQUE KEY `idx_admin_username` (`username`),
  UNIQUE KEY `idx_admin_phone_hash` (`phone_hash`),
  KEY `idx_admin_role` (`role`),
  KEY `idx_admin_is_active` (`is_active`),
  KEY `idx_admin_deleted_at` (`deleted_at`),
  KEY `idx_admin_legacy_user_id` (`legacy_user_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
