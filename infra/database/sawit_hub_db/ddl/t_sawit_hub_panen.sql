CREATE TABLE IF NOT EXISTS `t_sawit_hub_panen` (
  `id_panen` bigint unsigned NOT NULL AUTO_INCREMENT,
  `user_id` bigint unsigned NOT NULL,
  `id_lahan` bigint unsigned NOT NULL,
  `tanggal_panen` date NOT NULL,
  `luas_panen_ha` decimal(10,2) DEFAULT NULL,
  `jumlah_janjang` int DEFAULT NULL,
  `berat_kg` decimal(12,2) DEFAULT NULL,
  `berat_ton` decimal(12,4) GENERATED ALWAYS AS ((case when (`berat_kg` is not null) then (`berat_kg` / 1000) else NULL end)) STORED,
  `berat_rata_janjang` decimal(10,3) GENERATED ALWAYS AS ((case when ((`jumlah_janjang` > 0) and (`berat_kg` is not null)) then (`berat_kg` / `jumlah_janjang`) else NULL end)) STORED,
  `harga_per_kg` decimal(10,2) DEFAULT NULL,
  `total_pendapatan` decimal(14,2) GENERATED ALWAYS AS ((case when ((`berat_kg` is not null) and (`harga_per_kg` is not null)) then (`berat_kg` * `harga_per_kg`) else NULL end)) STORED,
  `biaya_panen` decimal(12,2) DEFAULT NULL,
  `hasil_bersih` decimal(14,2) GENERATED ALWAYS AS ((case when ((`berat_kg` is not null) and (`harga_per_kg` is not null)) then ((`berat_kg` * `harga_per_kg`) - coalesce(`biaya_panen`,0)) else NULL end)) STORED,
  `catatan` text,
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `deleted_at` datetime DEFAULT NULL,
  PRIMARY KEY (`id_panen`),
  UNIQUE KEY `idx_user_id_id_lahan_tanggal_panen` (`user_id`,`id_lahan`,`tanggal_panen`),
  KEY `idx_user_id` (`user_id`),
  KEY `idx_id_lahan` (`id_lahan`),
  KEY `idx_tanggal_panen` (`tanggal_panen`),
  KEY `idx_user_tanggal` (`user_id`,`tanggal_panen`),
  KEY `idx_deleted_at` (`deleted_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
