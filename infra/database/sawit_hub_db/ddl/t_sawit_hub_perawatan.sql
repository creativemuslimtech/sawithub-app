CREATE TABLE IF NOT EXISTS `t_sawit_hub_perawatan` (
  `id_perawatan` bigint unsigned NOT NULL AUTO_INCREMENT,
  `user_id` bigint unsigned NOT NULL,
  `id_lahan` bigint unsigned NOT NULL,
  `tanggal_perawatan` date NOT NULL,
  `jenis_perawatan` varchar(50) NOT NULL,
  `bahan` varchar(150) NOT NULL,
  `jumlah` decimal(10,2) DEFAULT NULL,
  `satuan` enum('kg','liter','gram','unit','zak','botol') NOT NULL DEFAULT 'kg',
  `harga_satuan` decimal(12,2) DEFAULT NULL,
  `total_harga_material` decimal(12,2) DEFAULT NULL,
  `biaya_pekerja` decimal(12,2) DEFAULT NULL,
  `total_biaya_perawatan` decimal(12,2) DEFAULT NULL,
  `keterangan` text,
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `deleted_at` datetime DEFAULT NULL,
  PRIMARY KEY (`id_perawatan`),
  UNIQUE KEY `idx_user_id_id_lahan_tanggal_perawatan_jenis_perawatan_bahan` (`user_id`,`id_lahan`,`tanggal_perawatan`,`jenis_perawatan`,`bahan`),
  KEY `idx_user_id` (`user_id`),
  KEY `idx_id_lahan` (`id_lahan`),
  KEY `idx_perawatan_tanggal` (`tanggal_perawatan`),
  KEY `idx_user_id_tanggal_perawatan` (`user_id`,`tanggal_perawatan` DESC),
  KEY `idx_user_id_id_lahan_tanggal_perawatan` (`user_id`,`id_lahan`,`tanggal_perawatan` DESC),
  KEY `idx_deleted_at` (`deleted_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
