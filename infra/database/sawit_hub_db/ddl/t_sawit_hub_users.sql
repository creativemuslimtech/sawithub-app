CREATE TABLE IF NOT EXISTS `t_sawit_hub_users` (
  `user_id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `public_id` varchar(36) NOT NULL,
  `username` varchar(50) NOT NULL,
  `email_hash` varchar(64) NOT NULL,
  `email_enc` text NOT NULL,
  `full_name_enc` text,
  `phone_enc` text,
  `phone_hash` varchar(64) DEFAULT NULL,
  `password_hash` varchar(255) NOT NULL,
  `role` enum('user','admin') NOT NULL DEFAULT 'user',
  `subscription_status` varchar(32) NOT NULL DEFAULT 'trialing',
  `trial_starts_at` datetime DEFAULT CURRENT_TIMESTAMP,
  `trial_ends_at` datetime DEFAULT ((now() + interval 14 day)),
  `subscription_starts_at` datetime DEFAULT NULL,
  `subscription_ends_at` datetime DEFAULT NULL,
  `last_payment_status` varchar(64) NOT NULL DEFAULT '',
  `midtrans_order_id` varchar(128) NOT NULL DEFAULT '',
  `plan_name` varchar(64) NOT NULL DEFAULT '',
  `plan_price` decimal(12,2) NOT NULL DEFAULT '0.00',
  `billing_exempt` tinyint(1) NOT NULL DEFAULT '0',
  `active_farm_limit` int NOT NULL DEFAULT '1',
  `current_active_farm_id` varchar(64) NOT NULL DEFAULT '',
  `trial_farm_create_used` int NOT NULL DEFAULT '0',
  `trial_panen_used` int NOT NULL DEFAULT '0',
  `trial_perawatan_used` int NOT NULL DEFAULT '0',
  `trial_jadwal_used` int NOT NULL DEFAULT '0',
  `trial_harvest_used` int NOT NULL DEFAULT '0',
  `trial_report_export_used` int NOT NULL DEFAULT '0',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `last_seen_at` datetime DEFAULT NULL,
  `deleted_at` datetime DEFAULT NULL,
  PRIMARY KEY (`user_id`),
  UNIQUE KEY `idx_public_id` (`public_id`),
  UNIQUE KEY `idx_email_hash_unique` (`email_hash`),
  UNIQUE KEY `idx_username_unique` (`username`),
  KEY `idx_phone_hash` (`phone_hash`),
  KEY `idx_deleted_at` (`deleted_at`),
  KEY `idx_deleted_at_user_id` (`deleted_at`,`user_id`),
  KEY `idx_deleted_at_last_seen_at` (`deleted_at`,`last_seen_at`),
  KEY `idx_role` (`role`),
  KEY `idx_subscription_status` (`subscription_status`),
  KEY `idx_midtrans_order_id` (`midtrans_order_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
