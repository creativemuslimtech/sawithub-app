CREATE TABLE IF NOT EXISTS `t_sawit_hub_jadwal_perawatan` (
  `id_jadwal_perawatan` bigint unsigned NOT NULL AUTO_INCREMENT,
  `user_id` bigint unsigned NOT NULL,
  `id_lahan` bigint unsigned NOT NULL,
  `jenis_perawatan` varchar(50) NOT NULL,
  `deskripsi` text,
  `frequensi_tipe` enum('mingguan','dua_mingguan','bulanan','dua_bulanan','tiga_bulanan','empat_bulanan','enam_bulanan','tahunan','dua_kali_tahunan','tiga_kali_tahunan','custom') NOT NULL DEFAULT 'bulanan',
  `frequensi_custom_hari` int DEFAULT NULL,
  `tanggal_mulai` date NOT NULL,
  `tanggal_akhir` date DEFAULT NULL,
  `estimasi_biaya` decimal(12,2) DEFAULT NULL,
  `is_active` tinyint(1) DEFAULT '1',
  `catatan` text,
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `deleted_at` datetime DEFAULT NULL,
  PRIMARY KEY (`id_jadwal_perawatan`),
  KEY `idx_user_id` (`user_id`),
  KEY `idx_id_lahan` (`id_lahan`),
  KEY `idx_user_id_is_active` (`user_id`,`is_active`),
  KEY `idx_user_id_id_lahan_is_active` (`user_id`,`id_lahan`,`is_active`),
  KEY `idx_tanggal_mulai` (`tanggal_mulai`),
  KEY `idx_deleted_at` (`deleted_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
